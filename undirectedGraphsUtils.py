# Adjacent list conversion

def adjacentListToAdjacentMatrix(adjacent_list=None):
    """Convert a 1-based adjacency list to a square adjacency matrix.

    Args:
        adjacent_list: A sequence of neighbor sequences. Row ``i`` describes
            node ``i + 1`` and neighbors are numbered from 1.

    Returns:
        A square matrix containing 1 for each listed adjacency and 0 otherwise.

    Raises:
        ValueError: If ``adjacent_list`` is not provided.
    """
    if adjacent_list == None:
        raise ValueError("Adjacent list required!")
    
    matrix = []
    for i in range(len(adjacent_list)):
        row = [0] * len(adjacent_list)
        for j in adjacent_list[i]:
            row[j - 1] = 1
        matrix.append(row)
    return matrix

def adjacentListToIncidentsMatrix(adjacent_list=None):
    """Convert a 1-based adjacency list to an incidence matrix.

    Each matrix column represents one undirected edge and has a 1 at each
    endpoint. An edge is included once, assuming the adjacency list is
    symmetric and contains no self-loops.

    Args:
        adjacent_list: A sequence of neighbor sequences. Rows and neighbors
            use 1-based node numbering.

    Returns:
        A sequence of vertex-length columns, one for each edge.

    Raises:
        ValueError: If ``adjacent_list`` is not provided.
    """
    if adjacent_list == None:
        raise ValueError("Adjacent list required!")
    
    matrix = []
    for i in range(len(adjacent_list)):
        for j in adjacent_list[i]:
            if j - 1 >= i:
                col = [0] * len(adjacent_list)
                col[i] = 1
                col[j-1] = 1
                matrix.append(col)
    return matrix

# Adjacent matrix conversion

def adjacentMatrixToIncidentsMatrix(adjacent_matrix=None):
    """Convert an adjacency matrix to an incidence matrix.

    Args:
        adjacent_matrix: A square adjacency matrix for an undirected graph.

    Returns:
        A sequence of vertex-length columns, one for each upper-triangle entry
        equal to 1; each column marks the two endpoints of its edge.

    Raises:
        ValueError: If ``adjacent_matrix`` is not provided.
    """
    if adjacent_matrix == None:
        raise ValueError("Adjacent matrix required!")
    
    matrix = []
    for i in range(len(adjacent_matrix)):
        for j in range(i + 1, len(adjacent_matrix)):
            if adjacent_matrix[i][j] == 1:
                col = [0] * len(adjacent_matrix)
                col[i] = 1
                col[j] = 1
                matrix.append(col)
    return matrix

def adjacentMatrixToAdjacentList(adjacent_matrix=None):
    """Convert an adjacency matrix to a 1-based adjacency list.

    Args:
        adjacent_matrix: A square matrix in which a value of 1 indicates an
            adjacency.

    Returns:
        A list whose row ``i`` contains the 1-based neighbors of node ``i + 1``.

    Raises:
        ValueError: If ``adjacent_matrix`` is not provided.
    """
    if adjacent_matrix == None:
        raise ValueError("Adjacent matrix required!")
    
    adj_list = []
    for i in range(len(adjacent_matrix)):
        row = []
        for j in range(len(adjacent_matrix)):
            if adjacent_matrix[i][j] == 1:
                row.append(j + 1)
        adj_list.append(row)
    return adj_list

# Incident matrix conversion

def incidentsMatrixToAdjacentList(incidents_matrix=None):
    """Convert an incidence matrix to a 1-based adjacency list.

    The matrix is expected as a sequence of columns, one per edge, with exactly
    two entries equal to 1 in each column.

    Args:
        incidents_matrix: A sequence of vertex-length edge columns.

    Returns:
        An adjacency list with nodes and neighbors numbered from 1.

    Raises:
        ValueError: If ``incidents_matrix`` is not provided.
    """
    if incidents_matrix == None:
        raise ValueError("Incidents matrix required!")
    
    matrix = [] * len(incidents_matrix[0])
    for _ in range(len(incidents_matrix[0])):
        matrix.append([] * len(incidents_matrix[0]))
    for i in incidents_matrix:
        first, second = -1,-1
        for j in range(len(incidents_matrix[0])):
            if i[j] == 1:
                if first == -1:
                    first = j
                else:
                    second = j
                    break
        matrix[first].append(second + 1)
        matrix[second].append(first + 1)
            

    return matrix

def incidentsMatrixToAdjacentMatrix(incidents_matrix=None):
    """Convert an incidence matrix to an adjacency matrix.

    The matrix is expected as a sequence of columns, one per edge, with exactly
    two entries equal to 1 in each column.

    Args:
        incidents_matrix: A sequence of vertex-length edge columns.

    Returns:
        A square adjacency matrix for the represented undirected graph.

    Raises:
        ValueError: If ``incidents_matrix`` is not provided.
    """
    if incidents_matrix == None:
        raise ValueError("Incidents matrix required!")
    
    matrix = [] * len(incidents_matrix[0])
    for _ in range(len(incidents_matrix[0])):
        matrix.append([0] * len(incidents_matrix[0]))
    for i in incidents_matrix:
        first, second = -1,-1
        for j in range(len(incidents_matrix[0])):
            if i[j] == 1:
                if first == -1:
                    first = j
                else:
                    second = j
                    break
        matrix[first][second] = 1
        matrix[second][first] = 1
            

    return matrix

