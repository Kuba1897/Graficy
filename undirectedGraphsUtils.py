def deleteNode(adjacent_list=None, node_num=None):
    """Remove a node's incident edges without removing its adjacency-list row.

    The input is copied and left unchanged. The selected node remains in the
    returned list as an empty row, so the node numbering and list length stay
    the same.

    Args:
        adjacent_list: An adjacency list whose node numbers start at 1.
        node_num: The 1-based number of the node whose edges should be removed.

    Returns:
        A copied adjacency list with all references to ``node_num`` removed.

    Raises:
        ValueError: If the adjacency list or node number is not provided.
    """
    if adjacent_list == None:
        raise ValueError("Adjacent list required!")
    if node_num == None:
        raise ValueError("Node number index [1...n] required!")
    node_num = node_num - 1
    # Create copy to not modify passed graph
    output_adjacent_list = [list(nodes) for nodes in adjacent_list]
    for connected_nodes in output_adjacent_list[node_num]:
        output_adjacent_list[connected_nodes - 1].remove(node_num + 1)
    output_adjacent_list[node_num] = []
    return output_adjacent_list

def deleteEdge(adjacent_list=None, edge=None):
    """Remove an undirected edge from a copied adjacency list.

    Args:
        adjacent_list: An adjacency list whose node numbers start at 1.
        edge: A two-item pair containing the 1-based endpoint numbers.

    Returns:
        A copied adjacency list with the edge removed from both endpoint rows.

    Raises:
        ValueError: If the adjacency list or a two-endpoint edge is not provided.
    """
    if adjacent_list == None:
        raise ValueError("Adjacent list required!")
    if edge == None or len(edge) != 2:
        raise ValueError("Edge in format [a,b] or (a,b), where a and b are nodes index 1..n required!")
    node1 = edge[0] - 1
    node2 = edge[1] - 1
    # Create copy to not modify passed graph
    output_adjacent_list = [list(nodes) for nodes in adjacent_list]
    output_adjacent_list[node1].remove(node2 + 1)
    output_adjacent_list[node2].remove(node1 + 1)
    return output_adjacent_list


