def load_graph_from_file(filename=None, fileFormat='auto'):
    """Load a graph from a text file and return its adjacency list.

    The file may contain an adjacency list (rows prefixed by node numbers), a
    square adjacency matrix, or an incidence matrix. Rows and node numbers in
    the returned adjacency list use 1-based numbering.

    Args:
        filename: Path to the graph text file.

    Returns:
        The loaded graph as a sorted adjacency list.

    Raises:
        ValueError: If ``filename`` is omitted or the file is empty.
        OSError: If the file cannot be opened or read.
    """
    if filename == None:
        raise ValueError("Filename is needed!")
    
    adjacent_list = []
    with open(filename, "r") as fp:
        lines = fp.readlines()
        match fileFormat:
            case 'auto':
                rows_num = len(lines)
                if rows_num == 0:
                    raise ValueError("Empty file!")
                cols_num = len(lines[0].split())

                if rows_num == 1: #sequence for graphical representation
                    sequence = [int(num) for num in lines[0].split(" ")]
                    status = checkIfGraphicSequence(sequence=sequence)
                    if status == False:
                        print("It's not graphical sequence")
                        raise ValueError("Sequence is not graphical!")
                    else:
                        print("It's graphical sequence")
                        adjacent_list = graphicalSequenceToAdjacentList(sequence=sequence)
                elif (lines[0].split())[0].find('.') != -1: # lines[0][0] have '.', e.g '1.' its adjacent list format
                    for index, line in enumerate(lines):
                        adjacent_list.append([])
                        for i in line.split()[1:]: #node index is not used
                            adjacent_list[index].append(int(i))
                elif cols_num == rows_num:
                    # First check if its incidents matrix (all cols would have two 1's only)
                    adjacent_matrix_type = [[int(val) for val in line.split()] for line in lines]
                    incicent_matrix_type = [list(col) for col in zip(*adjacent_matrix_type)]

                    incicent_matrix_form = True
                    for col in incicent_matrix_type:
                        if col.count(1) != 2:
                            incicent_matrix_form = False

                    if incicent_matrix_form:
                        adjacent_list = incidentsMatrixToAdjacentList(incicent_matrix_type)
                    else:
                        adjacent_list = adjacentMatrixToAdjacentList(adjacent_matrix_type)

                else: # Incidents matrix
                    rows = [[int(val) for val in line.split()] for line in lines]
                    incidents_matrix = [list(col) for col in zip(*rows)]
                    adjacent_list = incidentsMatrixToAdjacentList(incidents_matrix)

            case 'adj_matrix':
                adjacent_matrix_type = [[int(val) for val in line.split()] for line in lines]
                adjacent_list = adjacentMatrixToAdjacentList(adjacent_matrix_type)

            case 'adj_list':
                for index, line in enumerate(lines):
                    adjacent_list.append([])
                    for i in line.split()[1:]: #node index is not used
                        adjacent_list[index].append(int(i))

            case 'inc_matrix':
                rows = [[int(val) for val in line.split()] for line in lines]
                incidents_matrix = [list(col) for col in zip(*rows)]
                adjacent_list = incidentsMatrixToAdjacentList(incidents_matrix)

            case 'seq':
                sequence = [int(num) for num in lines[0].split(" ")]
                status = checkIfGraphicSequence(sequence=sequence)
                if status == False:
                    print("It's not graphical sequence")
                    raise ValueError("Sequence is not graphical!")
                else:
                    print("It's graphical sequence")
                    adjacent_list = graphicalSequenceToAdjacentList(sequence=sequence)

            case _:
                raise ValueError("Bad file format! Use -h for help")
        
    for row in adjacent_list:
        row.sort()
    return adjacent_list